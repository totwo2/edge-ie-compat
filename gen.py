#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Edge IE Compat - 生成器
读 sitelist.xml (唯一真源) -> 自动 version+1 -> 推导 ZoneMap 主机
-> 生成 dist/setup-ie-compat.bat (含 Edge 企业模式策略 + Intranet 区域 + ActiveX + 重启, 幂等)
仅在 Windows(Parallels VM) 以管理员运行。
"""
import os
import re
import sys
import xml.etree.ElementTree as ET

# ---- 安全校验: 防止站点 URL/模式破坏生成的 .bat 或注入命令 ----
ALLOWED_CM = {"IE8", "IE9", "IE11"}
ALLOWED_OI = {"IE11"}
# BAD_CHARS 说明:
#   " ' < > | & ^ %  -> 破坏 XML 属性 / 成为 cmd 命令连接符 / 变量展开
#   空格             -> host 是 reg 的裸参数, 空格会把值截断(已再给 /d 加引号做纵深防御)
#   \ ;              -> 非分隔符但无用途, 一并禁掉减少歧义
#   \n \r \t         -> 换行/回车/制表可破坏 .bat 行结构
BAD_CHARS = ["\"", "'", "<", ">", "|", "&", "^", "%", " ", "\\", ";", "\n", "\r", "\t"]
MARKERS = [":XML_START", ":XML_END"]


def validate_sites(sites):
    for s in sites:
        url = (s.get("url") or "").strip()
        if not url:
            print("ERROR: 存在空的 <site url>, 请补全网址")
            sys.exit(1)
        if any(c in url for c in BAD_CHARS):
            print(f"ERROR: 站点 URL 含非法字符, 会破坏生成的 .bat: {url!r}")
            sys.exit(1)
        if any(m in url for m in MARKERS):
            print(f"ERROR: 站点 URL 含保留标记, 会破坏 XML 提取: {url!r}")
            sys.exit(1)
        try:
            url.encode("ascii")
        except UnicodeEncodeError:
            print(f"ERROR: 站点 URL 含非 ASCII 字符, 生成的 .bat(GBK) 会乱码: {url!r}")
            sys.exit(1)
        cm = (s.findtext("compat-mode") or "").strip()
        if cm and cm not in ALLOWED_CM:
            print(f"ERROR: compat-mode 非法 (应为 IE8/IE9/IE11): {cm!r}")
            sys.exit(1)
        oi = (s.findtext("open-in") or "").strip()
        if oi and oi not in ALLOWED_OI:
            print(f"ERROR: open-in 非法 (应为 IE11): {oi!r}")
            sys.exit(1)

SKILL_DIR = os.path.dirname(os.path.abspath(__file__))
SITELIST = os.path.join(SKILL_DIR, "sitelist.xml")
DIST_DIR = os.path.join(SKILL_DIR, "dist")
OUT = os.path.join(DIST_DIR, "setup-ie-compat.bat")

BAT_TEMPLATE = r'''@echo off
chcp 936 >nul
setlocal enabledelayedexpansion

REM ============================================================
REM  Edge IE Compatibility One-Click Config (generated by edge-ie-compat skill)
REM  Usage: 右键以管理员身份运行, 然后重开 Edge
REM  本脚本幂等, 可安全重复运行
REM ============================================================

REM ---- 自提权: 请求管理员 ----
net session >nul 2>&1
if %errorlevel% neq 0 (
    echo Requesting administrator privileges...
    powershell -NoProfile -Command "Start-Process -FilePath '%~f0' -Verb RunAs"
    exit /b
)

echo.
echo [1/5] 创建 C:\IECompat 目录...
if not exist "C:\IECompat" mkdir "C:\IECompat"

echo [2/5] 写入企业模式站点列表 sitelist.xml ...
powershell -NoProfile -ExecutionPolicy Bypass -Command ^
  "$lines = Get-Content -LiteralPath '%~f0' -Encoding Default; " ^
  "$s = ($lines | Select-String '^:XML_START$' | Select-Object -First 1).LineNumber; " ^
  "$e = ($lines | Select-String '^:XML_END$' | Select-Object -First 1).LineNumber; " ^
  "$xmlText = ($lines[($s)..($e-2)] -join [Environment]::NewLine); " ^
  "[xml]$x = $xmlText; " ^
  "$x.Save('C:\IECompat\sitelist.xml'); " ^
  "Write-Host ('    Written, version=' + $x.'site-list'.version + ', sites=' + $x.'site-list'.site.Count)"
if errorlevel 1 goto :fail

echo [3/5] 配置 Edge 企业模式策略...
reg add "HKLM\SOFTWARE\Policies\Microsoft\Edge" /v InternetExplorerIntegrationLevel /t REG_DWORD /d 1 /f >nul
reg add "HKLM\SOFTWARE\Policies\Microsoft\Edge" /v InternetExplorerIntegrationSiteList /t REG_SZ /d "file:///C:/IECompat/sitelist.xml" /f >nul
reg add "HKLM\SOFTWARE\WOW6432Node\Policies\Microsoft\Edge" /v InternetExplorerIntegrationLevel /t REG_DWORD /d 1 /f >nul
reg add "HKLM\SOFTWARE\WOW6432Node\Policies\Microsoft\Edge" /v InternetExplorerIntegrationSiteList /t REG_SZ /d "file:///C:/IECompat/sitelist.xml" /f >nul

echo [4/5] 配置本地 Intranet 区域与 ActiveX...
:: ZoneMap 范围由站点列表自动推导
__ZONEMAP__
reg add "HKCU\Software\Microsoft\Windows\CurrentVersion\Internet Settings\Zones\1" /v 1200 /t REG_DWORD /d 1 /f >nul
reg add "HKCU\Software\Microsoft\Windows\CurrentVersion\Internet Settings\Zones\1" /v 1201 /t REG_DWORD /d 0 /f >nul
reg add "HKCU\Software\Microsoft\Windows\CurrentVersion\Internet Settings\Zones\1" /v 1400 /t REG_DWORD /d 1 /f >nul
reg add "HKCU\Software\Microsoft\Windows\CurrentVersion\Internet Settings\Zones\1" /v 1402 /t REG_DWORD /d 1 /f >nul
reg add "HKCU\Software\Microsoft\Windows\CurrentVersion\Internet Settings\Zones\1" /v 1405 /t REG_DWORD /d 1 /f >nul

echo [5/5] 重启 Edge 以生效...
REM 注意: 会强制结束所有 Edge 进程, 请先保存 Edge 中所有未保存的内容
taskkill /F /IM msedge.exe /T >nul 2>&1

echo.
echo ============================================================
echo  配置完成! 重新打开 Edge 并在 IE 模式下验证内网站点.
echo  在 edge://compat 查看站点列表与版本号.
echo  若本机 Edge 由 IT 组策略(GPO)统一下发, 本脚本写入的策略
echo  可能被组策略覆盖; 此时需请 IT 把内网站点加入企业模式站点列表.
echo ============================================================
echo.
pause
exit /b 0

:fail
echo.
echo 配置失败, 请检查后重试.
pause
exit /b 1

:XML_START
__XML__
:XML_END
'''


def derive_hosts(urls):
    hosts = []
    for url in urls:
        url = url.strip()
        if not url:
            continue
        host = url.split("://")[-1].split("/")[0].split(":")[0]
        if host and host not in hosts:
            hosts.append(host)
    return hosts


def main():
    if not os.path.exists(SITELIST):
        print(f"ERROR: 找不到 {SITELIST}")
        sys.exit(1)

    with open(SITELIST, "r", encoding="utf-8") as f:
        txt = f.read()

    # 解析站点 (校验 + 推导)
    try:
        root = ET.fromstring(txt)
    except ET.ParseError as e:
        print(f"ERROR: sitelist.xml 不是合法 XML: {e}")
        sys.exit(1)

    sites = root.findall("site")
    if not sites:
        print("ERROR: sitelist.xml 没有任何 <site>, 请先用 add 命令添加站点. 已中止生成, 避免生成清空列表的脚本.")
        sys.exit(1)
    validate_sites(sites)

    urls = [(s.get("url") or "").strip() for s in sites]
    hosts = derive_hosts(urls)

    # 自动 version+1 (正则, 保留注释); IGNORECASE 兼容 VERSION= 这种写法
    m = re.search(r'<site-list[^>]*\sversion="(\d+)"', txt, re.IGNORECASE)
    if not m:
        print("ERROR: sitelist.xml 缺少 version 属性")
        sys.exit(1)
    ver = int(m.group(1)) + 1
    txt2 = re.sub(r'(<site-list[^>]*\sversion=")\d+(")',
                  r'\g<1>' + str(ver) + r'\g<2>', txt, flags=re.IGNORECASE)
    with open(SITELIST, "w", encoding="utf-8") as f:
        f.write(txt2)

    # 序列化站点列表 XML (用于嵌入 .bat)
    xml_lines = ['<?xml version="1.0" encoding="UTF-8"?>',
                 f'<site-list version="{ver}">']
    for i, s in enumerate(sites):
        # 与 validate_sites() 保持一致: 生成侧同样 strip, 避免首尾空白泄漏进 XML 与 host
        url = (s.get("url") or "").strip()
        cm = (s.findtext("compat-mode") or "IE9").strip()
        oi = (s.findtext("open-in") or "IE11").strip()
        xml_lines.append(
            f'  <site url="{url}"><compat-mode>{cm}</compat-mode><open-in>{oi}</open-in></site>')
    xml_lines.append('</site-list>')
    xml_block = "\n".join(xml_lines)

    # 推导 ZoneMap 注册表项
    zonemap = []
    # 清理旧 Range* 键: 删站/改顺序后, 旧的高序号 Range(如 Range5/6/7) 会残留于注册表,
    # 导致已删站点仍被划入 Intranet 区. 先清 Range3..99(只清本工具写入区间, 保留系统 Range1/Range2),
    # 再按当前列表重建, 保证幂等且无残留.
    zonemap.append(
        'for /L %%n in (3,1,99) do reg delete '
        '"HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Internet Settings\\ZoneMap\\Ranges\\Range%%n" '
        '/f >nul 2>&1')
    for i, host in enumerate(hosts):
        r = 3 + i
        base = f'HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Internet Settings\\ZoneMap\\Ranges\\Range{r}'
        # /d 的值加引号: 纵深防御, 即便将来 BAD_CHARS 漏拦也不会把 host 截断
        zonemap.append(f'reg add "{base}" /v Range /t REG_SZ /d "{host}" /f >nul')
        zonemap.append(f'reg add "{base}" /v http /t REG_DWORD /d 1 /f >nul')
        zonemap.append(f'reg add "{base}" /v https /t REG_DWORD /d 1 /f >nul')
    zonemap_block = "\n".join(zonemap) if zonemap else ":: (no hosts)"

    bat = BAT_TEMPLATE.replace("__ZONEMAP__", zonemap_block).replace("__XML__", xml_block)

    os.makedirs(DIST_DIR, exist_ok=True)
    # 以 GBK(cp936) 写入, 匹配原 .bat 中文与 chcp 936 控制台
    # errors="strict": 若将来模板引入 GBK 无法编码的字符(如 emoji/生僻字), 显式报错
    # 而非静默替换成 "?" 导致 URL 被改坏。动态内容(URL/host)已被 ASCII 校验拦截,
    # 正常路径不会触发。
    try:
        with open(OUT, "w", encoding="gbk", errors="strict") as f:
            f.write(bat)
    except UnicodeEncodeError as e:
        print(f"ERROR: 生成内容含 GBK 无法编码的字符, 已中止(避免产出损坏脚本): {e}")
        sys.exit(1)

    print(f"Generated {OUT}")
    print(f"  version={ver}, sites={len(sites)}, zonemap_hosts={len(hosts)}")


if __name__ == "__main__":
    main()
